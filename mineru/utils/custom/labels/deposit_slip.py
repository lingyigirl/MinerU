"""定期存单标签词典。

银行定期存款单常见的 KVP 字段，用于 OCR 文本匹配和标准化。
正则模式支持 OCR 常见误识别（形近字、漏字、多字），用字符组容错。
"""

from __future__ import annotations

# (OCR 正则匹配模式, 标准化标签名)
# 模式支持 OCR 常见误识别（形近字、漏字），用字符组容错
DEPOSIT_SLIP_LABELS: list[tuple[str, str]] = [
    # ---- 机构信息 ----
    (r"开户.?[机构行处银凯](?:名称)?", "开户机构名称"),
    (r"开户[机构行处银凯]", "开户机构名称"),
    # ---- 编号 ----
    (r"单[据证][编號号][码碼]?", "单据编号"),
    (r"[编號号][码碼号]", "单据编号"),
    (r"批[次号號][码碼]?", "批次号"),
    # ---- 存款人 ----
    (r"户[名姓名]", "户名"),
    (r"客[户户][号號][码碼]?", "客户号"),
    # ---- 账号 ----
    (r"账[号號户][号碼]?", "账号"),
    (r"账[号號户]", "账号"),
    # ---- 产品 ----
    (r"产[品品][名名称][称稱]?", "产品名称"),
    (r"币[种別种]", "币种"),
    # ---- 金额 ----
    (r"存[入款人]金[额額](?:[(（].*大[写寫].*[)）])?", "存入金额(大写)"),
    (r"(?:存入)?金[额額][(（].*大[写寫].*[)）]", "存入金额(大写)"),
    (r"大[写寫]金[额額]", "存入金额(大写)"),
    (r"存[入款人]金[额額](?:[(（].*小[写寫].*[)）])?", "存入金额(小写)"),
    (r"(?:存入)?金[额額][(（].*小[写寫].*[)）]", "存入金额(小写)"),
    (r"小[写寫]金[额額]", "存入金额(小写)"),
    # ---- 日期 ----
    (r"开[户户][日□口]", "开户日"),
    (r"起[息息][日□口]?", "起息日"),
    (r"存[期期]", "存期"),
    # 重要：以下以"到"开头的模式，必须将更具体（更长/强制后缀）的模式排在
    # "到期日"之前。因为"到[期期][日□口]?"的最后一组可选，会降级匹配前缀
    # "到期"（如把"到期息"错配为"到期日"）。
    (r"预[估估]?到[期期]本[息息]", "预估到期本息"),
    (r"到[期期]本[息息]", "预估到期本息"),
    (r"到[期期]利[息息]", "到期利息"),
    (r"到[期期]息", "到期利息"),
    (r"到[期期][日□口]?", "到期日"),
    (r"签[发發][日□口](?:期)?", "签发日期"),
    # 利率（"利"字只出现在此标签中）
    # ---- 转存/密码 ----
    (r"自[动動]转[存存]", "自动转存"),
    (r"(?:是否)?[凭憑]密[码碼盃]", "是否凭密码"),
    (r"密[码碼盃]", "是否凭密码"),
    # ---- 经办 ----
    (r"(?:存[入款人]时)?经[办辦](?!.*授[权權复])", "存入时经办"),
    (r"存[入款人]时.?经[办辦]", "存入时经办"),
    (r"操[作做][员貝](?:[代碼码编]?[码碼]?)?", "操作员代码"),
    (r"复[核械](?:[(（].*授[权權].*[)）])?", "复核(授权)"),
    # ---- 签章 ----
    (r"客[户戶]签[章章]", "客户签章"),
    (r"业[务務]公[章章]", "业务公章"),
    # ---- 支取方式 ----
    (r"支[取付]方[式试][式试]?", "支取方式"),
]
